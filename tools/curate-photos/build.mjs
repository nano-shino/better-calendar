// Step 2 of curating automatic photos: turn hand-picked candidate indexes into
// js/curated.js, checking that each image URL still loads.
//
//   node tools/curate-photos/build.mjs
//
// PICKS lists, per theme, the indexes (as labelled on the contact sheets) of the
// photos that clearly show that kind of event. Pick 2-3 per theme. Reject anything
// ambiguous: a wrong photo is worse than no photo.
import { readFileSync, writeFileSync } from "node:fs";

const all = JSON.parse(readFileSync(new URL("candidates.json", import.meta.url), "utf8"));
const OUT_FILE = new URL("../../js/curated.js", import.meta.url);

const PICKS = {
  meeting: [0, 5, 15], gym: [0, 2, 5], run: [0, 7, 9], yoga: [8, 11, 14], swim: [0, 1, 5],
  flight: [1, 2, 9], train: [1, 7, 15], hike: [2, 6, 8], beach: [2, 12, 13], coffee: [0, 5, 12],
  lunch: [0, 9, 11], dinner: [0, 5, 7], birthday: [2, 8, 14], dentist: [1, 2, 3], doctor: [0, 1, 3],
  concert: [0, 2, 7], movie: [1, 4], study: [1, 9, 12], market: [2, 8, 14], soccer: [2, 4, 10],
  tennis: [3, 7, 15], basketball: [3, 11, 12], travel: [0, 9, 14], haircut: [1, 9, 13], cycling: [1, 3, 15],
  wedding: [2, 5, 13], games: [0, 1, 6], cooking: [7, 10, 13], dog: [1, 6],
};

async function ok(u) {
  try {
    const r = await fetch(u, { method: "GET", headers: { Range: "bytes=0-1023" }, redirect: "follow" });
    return r.ok && (r.headers.get("content-type") || "").startsWith("image/");
  } catch { return false; }
}

const out = {};
for (const [k, idxs] of Object.entries(PICKS)) {
  if (!all[k]) { console.error(`No candidates for "${k}". Run fetch.mjs ${k} first.`); process.exit(1); }
  out[k] = [];
  for (const i of idxs) {
    const c = all[k][i];
    const [fullOk, thumbOk] = await Promise.all([ok(c.url), ok(c.thumb)]);
    if (!fullOk && !thumbOk) { console.log("DROP (doesn't load)", k, i); continue; }
    const license = `CC ${(c.license || "").toUpperCase()} ${c.lv || ""}`.replace("CC CC0", "CC0").replace("CC PDM", "Public domain").trim();
    out[k].push({ url: fullOk ? c.url : c.thumb, thumb: thumbOk ? c.thumb : c.url, credit: { by: c.by, license, link: c.link } });
    if (!fullOk) console.log("thumb-only", k, i);
  }
}
const body = `// Hand-checked photos for common kinds of events (Openverse, Creative Commons).
// Each one was reviewed by eye, so automatic photos only appear when they clearly fit.
// Generated by tools/curate-photos/build.mjs. Don't edit by hand.
export const CURATED = ${JSON.stringify(out, null, 1)};
`;
writeFileSync(OUT_FILE, body);
console.log("themes", Object.keys(out).length, "photos", Object.values(out).flat().length);
